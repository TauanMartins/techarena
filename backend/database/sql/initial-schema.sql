-- Consolidated PostgreSQL schema from the Laravel migrations in backend.old.
CREATE SCHEMA IF NOT EXISTS extensions;
CREATE EXTENSION IF NOT EXISTS postgis WITH SCHEMA extensions;
-- The location column uses whichever PostGIS schema is present on the target.
SET LOCAL search_path TO extensions, public;

CREATE TABLE public.permission (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug varchar(255) NOT NULL UNIQUE,
    symbol char(1) NOT NULL UNIQUE
);

CREATE TABLE public.users (
    id uuid PRIMARY KEY,
    name varchar(150),
    email varchar(150) UNIQUE,
    username varchar(45) UNIQUE,
    dt_birth date,
    gender char(1),
    image varchar(150),
    permission_id bigint REFERENCES public.permission (id) ON DELETE SET NULL,
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.friend (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id uuid NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    addressee_id uuid NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    status varchar(255) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'accepted', 'blocked')),
    created_at timestamp without time zone,
    updated_at timestamp without time zone,
    CONSTRAINT friend_requester_addressee_unique UNIQUE (requester_id, addressee_id),
    CONSTRAINT friend_no_self_relationship CHECK (requester_id <> addressee_id)
);

CREATE TABLE public.preference (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    desc_preference varchar(45) NOT NULL UNIQUE,
    default_value varchar(45)
);

CREATE TABLE public.user_preference (
    user_id uuid NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    preference_id bigint NOT NULL REFERENCES public.preference (id) ON DELETE CASCADE,
    value varchar(45),
    PRIMARY KEY (user_id, preference_id)
);

CREATE TABLE public.sport (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(150) NOT NULL UNIQUE,
    default_value_player_numbers integer NOT NULL
);

CREATE TABLE public.material (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description varchar(250) NOT NULL
);

CREATE TABLE public.sport_material (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sport_id bigint NOT NULL REFERENCES public.sport (id) ON DELETE CASCADE,
    material_id bigint NOT NULL REFERENCES public.material (id) ON DELETE CASCADE,
    related_to_local boolean NOT NULL,
    CONSTRAINT unique_sport_material UNIQUE (sport_id, material_id)
);

CREATE TABLE public.arena (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    address varchar(150) NOT NULL,
    lat numeric(10, 7) NOT NULL,
    longitude numeric(11, 7) NOT NULL,
    image varchar(150),
    is_league_only boolean NOT NULL DEFAULT false
);

CREATE TABLE public.sport_arena (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sport_id bigint NOT NULL REFERENCES public.sport (id) ON DELETE CASCADE,
    arena_id bigint NOT NULL REFERENCES public.arena (id) ON DELETE CASCADE,
    CONSTRAINT unique_sport_arena UNIQUE (sport_id, arena_id)
);

CREATE TABLE public.schedule (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    horary time without time zone NOT NULL UNIQUE
);

CREATE TABLE public.league (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(45) NOT NULL,
    description varchar(500),
    league_number bigint NOT NULL UNIQUE,
    image varchar(150)
);

CREATE TABLE public.appointment (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organizer_id uuid NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    title varchar(100) NOT NULL,
    description text,
    scheduled_at timestamp without time zone NOT NULL,
    status varchar(255) NOT NULL DEFAULT 'scheduled'
        CHECK (status IN ('scheduled', 'in_progress', 'finished', 'canceled')),
    location geometry(Point),
    max_players integer,
    created_at timestamp without time zone,
    updated_at timestamp without time zone,
    deleted_at timestamp without time zone
);

CREATE TABLE public.user_appointment (
    appointment_id bigint NOT NULL REFERENCES public.appointment (id) ON DELETE CASCADE,
    user_id uuid NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    holder boolean NOT NULL DEFAULT true,
    PRIMARY KEY (appointment_id, user_id)
);

-- The Laravel table was named prefered_sports; the final migration renamed it.
CREATE TABLE public.user_sport (
    user_id uuid NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    sport_id bigint NOT NULL REFERENCES public.sport (id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, sport_id)
);

CREATE TABLE public.team (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(45) NOT NULL,
    description text,
    image varchar(255),
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.league_team (
    team_id bigint NOT NULL REFERENCES public.team (id) ON DELETE CASCADE,
    league_id bigint NOT NULL REFERENCES public.league (id) ON DELETE CASCADE,
    PRIMARY KEY (team_id, league_id)
);

CREATE TABLE public.user_team (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id uuid NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    team_id bigint NOT NULL REFERENCES public.team (id) ON DELETE CASCADE,
    role varchar(20) NOT NULL DEFAULT 'member',
    created_at timestamp without time zone,
    updated_at timestamp without time zone,
    CONSTRAINT user_team_user_team_unique UNIQUE (user_id, team_id)
);

CREATE TABLE public.appointment_result (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id bigint NOT NULL REFERENCES public.appointment (id) ON DELETE CASCADE,
    winner_team_id bigint REFERENCES public.team (id) ON DELETE SET NULL,
    loser_team_id bigint REFERENCES public.team (id) ON DELETE SET NULL,
    winner_score integer,
    loser_score integer,
    notes text,
    created_at timestamp without time zone,
    updated_at timestamp without time zone,
    CONSTRAINT appointment_result_one_per_appointment UNIQUE (appointment_id),
    CONSTRAINT appointment_result_scores_non_negative CHECK (
        (winner_score IS NULL OR winner_score >= 0)
        AND (loser_score IS NULL OR loser_score >= 0)
    ),
    CONSTRAINT appointment_result_different_teams CHECK (
        winner_team_id IS NULL OR loser_team_id IS NULL OR winner_team_id <> loser_team_id
    ),
    CONSTRAINT appointment_result_team_pair CHECK ((winner_team_id IS NULL) = (loser_team_id IS NULL)),
    CONSTRAINT appointment_result_score_pair CHECK ((winner_score IS NULL) = (loser_score IS NULL))
);

CREATE UNIQUE INDEX friend_unique_unordered_pair
    ON public.friend (LEAST(requester_id, addressee_id), GREATEST(requester_id, addressee_id));
CREATE INDEX friend_requester_id_index ON public.friend (requester_id);
CREATE INDEX friend_addressee_id_index ON public.friend (addressee_id);
CREATE INDEX appointment_organizer_id_index ON public.appointment (organizer_id);
CREATE INDEX appointment_result_winner_team_id_index ON public.appointment_result (winner_team_id);
CREATE INDEX appointment_result_loser_team_id_index ON public.appointment_result (loser_team_id);
CREATE INDEX user_preference_preference_id_index ON public.user_preference (preference_id);
CREATE INDEX user_sport_sport_id_index ON public.user_sport (sport_id);
CREATE INDEX user_appointment_user_id_index ON public.user_appointment (user_id);
CREATE INDEX league_team_league_id_index ON public.league_team (league_id);
CREATE INDEX sport_material_material_id_index ON public.sport_material (material_id);
CREATE INDEX sport_arena_arena_id_index ON public.sport_arena (arena_id);
CREATE INDEX user_team_team_id_index ON public.user_team (team_id);
